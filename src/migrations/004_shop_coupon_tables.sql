-- Keep shop promotions separate from salon subscription coupons.
CREATE TABLE IF NOT EXISTS shop_coupons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE CHECK (code = upper(code)),
    type TEXT NOT NULL CHECK (type IN ('percent', 'flat')),
    value INTEGER NOT NULL CHECK (
        (type = 'percent' AND value BETWEEN 1 AND 100) OR
        (type = 'flat' AND value > 0)
    ),
    min_order_paise BIGINT NOT NULL DEFAULT 0 CHECK (min_order_paise >= 0),
    max_discount_paise BIGINT CHECK (max_discount_paise IS NULL OR max_discount_paise >= 0),
    usage_limit INTEGER CHECK (usage_limit IS NULL OR usage_limit >= 0),
    per_user_limit INTEGER CHECK (per_user_limit IS NULL OR per_user_limit >= 0),
    used_count INTEGER NOT NULL DEFAULT 0 CHECK (used_count >= 0),
    starts_at TIMESTAMPTZ,
    ends_at TIMESTAMPTZ,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (ends_at IS NULL OR starts_at IS NULL OR ends_at > starts_at)
);

CREATE TABLE IF NOT EXISTS shop_coupon_redemptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coupon_id BIGINT NOT NULL REFERENCES shop_coupons(id) ON DELETE RESTRICT,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS shop_coupon_redemptions_user_idx
    ON shop_coupon_redemptions (coupon_id, user_id);

ALTER TABLE orders DROP CONSTRAINT IF EXISTS orders_coupon_id_fkey;
ALTER TABLE orders ADD CONSTRAINT orders_shop_coupon_id_fkey
    FOREIGN KEY (coupon_id) REFERENCES shop_coupons(id) ON DELETE SET NULL;

ALTER TABLE shop_coupon_reservations DROP CONSTRAINT IF EXISTS shop_coupon_reservations_coupon_id_fkey;
ALTER TABLE shop_coupon_reservations ADD CONSTRAINT shop_coupon_reservations_shop_coupon_id_fkey
    FOREIGN KEY (coupon_id) REFERENCES shop_coupons(id) ON DELETE RESTRICT;
