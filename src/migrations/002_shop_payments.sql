-- Payment flow additions. Safe to run after the initial shop schema.
CREATE SEQUENCE IF NOT EXISTS shop_order_number_seq START WITH 1;

CREATE TABLE IF NOT EXISTS shop_coupon_reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coupon_id BIGINT NOT NULL REFERENCES shop_coupons(id) ON DELETE RESTRICT,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL,
    released_at TIMESTAMPTZ,
    consumed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS shop_coupon_reservations_active_idx
    ON shop_coupon_reservations (coupon_id, user_id, expires_at)
    WHERE released_at IS NULL AND consumed_at IS NULL;

CREATE INDEX IF NOT EXISTS stock_reservations_order_idx
    ON stock_reservations (order_item_id);
